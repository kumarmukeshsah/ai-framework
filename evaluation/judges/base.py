"""Base judge for LLM-as-Judge evaluations."""
from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Any


@dataclass
class JudgeResult:
    """Result from a judge evaluation."""

    score: float  # 0.0 to 1.0
    reasoning: str = ""
    feedback: str = ""
    metadata: dict[str, Any] = field(default_factory=dict)

    def passed(self, threshold: float = 0.7) -> bool:
        """Check if the result passes a threshold."""
        return self.score >= threshold


class BaseJudge(ABC):
    """Abstract base class for LLM-as-Judge evaluations."""

    def __init__(self, name: str):
        self.name = name

    @abstractmethod
    async def evaluate(
        self,
        input_text: str,
        actual_output: str,
        expected_output: str | None = None,
        **kwargs: Any,
    ) -> JudgeResult:
        """Evaluate the quality of an actual output against expected output.

        Args:
            input_text: The original input/prompt
            actual_output: The actual output generated by the system
            expected_output: The expected/reference output (optional)
            **kwargs: Additional evaluation parameters

        Returns:
            JudgeResult with score, reasoning, and feedback
        """
        ...
